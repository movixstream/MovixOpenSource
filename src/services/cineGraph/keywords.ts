/** Vrai pour un mot-clé TMDB qui ne dit rien du thème de l'œuvre. */
export function isMetaKeyword(name: string): boolean {
  const key = name.trim().toLowerCase();
  if (!key) return true;
  // « based on novel or book », « based on manga »… : la source, pas le sujet.
  if (key.startsWith('based on ') || key.startsWith('inspired by ')) return true;
  if (key.endsWith(' adaptation')) return true;
  return META_KEYWORDS.has(key);
}

