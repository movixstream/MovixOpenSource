const ROMAN = ['', 'I', 'II', 'III', 'IV', 'V', 'VI', 'VII', 'VIII', 'IX', 'X', 'XI', 'XII', 'XIII', 'XIV',
  'XV', 'XVI', 'XVII', 'XVIII', 'XIX', 'XX', 'XXI'];

/**
 * Libellé d'un mot-clé dans la langue de l'interface. Seul le français a un
 * dictionnaire ; ailleurs, ou pour un mot inconnu, on garde le nom TMDB.
 */
export function keywordLabel(name: string, lang: string): string {
  // Certains noms TMDB traînent une espace finale (« political intrigue »).
  const trimmed = name.trim();
  if (!lang.toLowerCase().startsWith('fr')) return trimmed;
  const key = trimmed.toLowerCase();
  const label = FR_LABELS.get(key);
  if (label) return label;
  // « 1980s » → « années 1980 », « 19th century » → « XIXe siècle » : une
  // règle couvre toutes les décennies et tous les siècles.
  const decade = /^(\d{3}0)s$/.exec(key);
  if (decade) return `années ${decade[1]}`;
  const century = /^(\d{1,2})(?:st|nd|rd|th) century$/.exec(key);
  const roman = century ? ROMAN[Number(century[1])] : undefined;
  if (roman) return roman === 'I' ? 'Ier siècle' : `${roman}e siècle`;
  return trimmed;
}
